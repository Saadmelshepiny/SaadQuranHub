_D = {}


def _dicts():
    """-> (labels, values) of the chosen language, keyed by the Arabic text."""
    lang = LANG[0]
    if lang not in _D:
        x = XL.get(lang, {})
        _D[lang] = (dict((a, x.get(e, e)) for a, e in EN.items()), dict((a, x.get(e, e)) for a, e in VALUES.items()))
    return _D[lang]


def on():
    return LANG[0] != "ar"


def T(text):
    """Arabic UI label -> the chosen language (English, French, Turkish, Urdu)."""
    if not on() or not text:
        return text
    try:
        return _t(text)
    except Exception:
        return text


def _t(text):
    EN, VALUES = _dicts()
    if text in EN:
        return EN[text]
    s = text
    lead = u""
    m = _LEAD.match(s)
    if m:
        lead, s = m.group(1), s[m.end():]
    tail = u""
    for end in (u" ...", u"...", u"  ▶"):
        if s.endswith(end):
            s, tail = s[:-len(end)], end
            break
    if s in EN:
        return lead + EN[s] + tail
    if u":" in s:
        head, val = s.split(u":", 1)
        h = EN.get(head.strip())
        if h:
            v = val.strip()
            v2 = VALUES.get(v, EN.get(v, v))
            return u"%s%s: %s%s" % (lead, h, v2, tail)
    m = re.match(u"^(.*?)\\s*(\\([^()]*\\))$", s)
    if m and m.group(1) in EN:
        return lead + EN[m.group(1)] + u" " + m.group(2) + tail
    return text
